#!/usr/bin/env node
// Generates reports/final-matrix.md — the final audit matrix required by the TO-DO:
//   URL | Locale | Status | Findings | Fix Applied | Evidence | Test Result | Commit
// from reports/seo-audit.json (run `npm run seo:audit` first). "Fix applied" and "Commit" are per PAGE TYPE (the
// phases that changed that kind of page), not per URL: the work was done by page type, never one URL at a time.
// Status is LOCAL TESTED at best; nothing here is PRODUCTION VERIFIED.
const fs = require('fs');
const { results } = JSON.parse(fs.readFileSync('reports/seo-audit.json', 'utf8'));
const FIX = {
  home: ['Islands-only nav (D1/D2), localized metadata', 'fecacc5, c095bf1, 91988e2'],
  service: ['Keyword-led title/H1/meta, 40-60-word answer, long-form sections, THB price table with included/excluded, schema catalog, chat links', '900428a, 6242986, 91988e2, 6e46cc1'],
  location: ['Direct answer 40-60 words, Place + ImageObject schema, localized headings, chat links', '6242986, 91988e2, 6e46cc1'],
  project: ['Concept labels, diagram + palette, Concept schema, localized labels', 'aece8dc, 91988e2'],
  article: ['Localized index metadata (journal)', 'c095bf1'],
  about: ['Direct answer, localized metadata', '6242986, 91988e2'],
  process: ['Direct answer, localized stage labels', '6242986, 91988e2'],
  contact: ['Review step, reply language, whitelists, attribution, ContactPage schema', '61d61cb, 6e46cc1'],
  plan: ['New page: service finder, estimator, timeline', '6e46cc1'],
  checklist: ['New page: printable checklist', '6e46cc1'],
  privacy: ['Translated, planning-tool/attribution section', '4011129'],
  terms: ['Translated', '4011129'],
  cookies: ['Translated', '4011129'],
  accessibility: ['Translated', '4011129'],
  'editorial-policy': ['Translated', '4011129'],
  'thank-you': ['Localized', 'c095bf1'],
};
const typeOf = (u) => { const r = u.replace(/^\/(ru|th|he)\//, '/'); return r === '/' ? 'home' : /^\/services\/./.test(r) ? 'service' : /^\/locations\/./.test(r) ? 'location' : /^\/projects\/./.test(r) ? 'project' : /^\/journal\/./.test(r) ? 'article' : r.replace(/\//g, '') || 'home'; };
const by = {};
for (const r of results) { if (r.url === '/robots.txt' || !r.url) continue; (by[r.url] = by[r.url] || []).push(r); }
let md = '# Final audit matrix (generated by `npm run seo:matrix`; local build only, not production verified)\n\n| URL | Locale | Status | Findings | Fix applied (by page type) | Evidence | Test result | Commit(s) |\n|---|---|---|---|---|---|---|---|\n';
for (const url of Object.keys(by).sort()) {
  const rs = by[url];
  const fails = rs.filter((r) => r.status === 'FAIL'), warns = rs.filter((r) => r.status === 'WARNING');
  const t = typeOf(url);
  const [fix, commits] = FIX[t] || ['-', '-'];
  const loc = (url.match(/^\/(ru|th|he)\//) || [, 'en'])[1];
  const status = fails.length ? 'FAILED' : 'LOCAL TESTED';
  const findings = [...fails, ...warns].map((r) => `${r.status === 'FAIL' ? 'FAIL' : 'warn'}: ${r.check}`).filter((v, i, a) => a.indexOf(v) === i).join('; ') || 'none';
  md += `| ${url} | ${loc} | ${status} | ${findings} | ${fix} | reports/seo-audit.json (${rs.length} checks) | ${fails.length ? 'FAIL' : warns.length ? 'PASS with warnings' : 'PASS'} | ${commits} |\n`;
}
fs.writeFileSync('reports/final-matrix.md', md);
console.log('reports/final-matrix.md written,', Object.keys(by).length, 'URLs');
